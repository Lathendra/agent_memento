-- P0 Raw: land staged Parquet into RAW.BRAINTRUST_SPANS. JSON text payloads parsed to VARIANT.
USE ROLE ATTENDEE_ROLE;
USE WAREHOUSE DEFAULT_WH;
USE SCHEMA AGENT_MEMENTO.RAW;

CREATE FILE FORMAT IF NOT EXISTS PARQUET_FF TYPE = PARQUET;

CREATE TABLE IF NOT EXISTS BRAINTRUST_SPANS (
    ID                  STRING,
    XACT_ID             NUMBER(38,0),
    PAGINATION_KEY      STRING,
    CREATED             TIMESTAMP_NTZ(6),
    SPAN_ID             STRING,
    ROOT_SPAN_ID        STRING,
    SPAN_PARENTS        VARIANT,
    IS_ROOT             BOOLEAN,
    PROJECT_ID          STRING,
    ORG_ID              STRING,
    LOG_ID              STRING,
    INPUT               VARIANT,
    OUTPUT              VARIANT,
    EXPECTED            VARIANT,
    ERROR               VARIANT,
    METADATA            VARIANT,
    METRICS             VARIANT,
    SCORES              VARIANT,
    SPAN_ATTRIBUTES     VARIANT,
    TAGS                VARIANT,
    AUDIT_DATA          VARIANT,
    CONTEXT             VARIANT,
    ORIGIN              VARIANT,
    CLASSIFICATIONS     VARIANT,
    COMMENTS            VARIANT,
    FACETS              VARIANT,
    ASYNC_SCORING_STATE VARIANT,
    PROJECT_NAME        STRING,
    EVENT_DT            DATE,
    SOURCE_SYSTEM       STRING,
    SOURCE_VERSION_KEY  NUMBER(3,0),
    ROW_HASH            STRING,
    FIELD_COUNT         NUMBER(38,0),
    _INGEST_METHOD      STRING,
    _INGEST_RUN_ID      STRING,
    _INGEST_BATCH_ID    STRING,
    _SOURCE_FILE        STRING,
    _LOADED_AT          TIMESTAMP_NTZ(6),
    _STAGE_FILE         STRING
)
CLUSTER BY (EVENT_DT)
COMMENT = 'Braintrust agent spans, landed unchanged (synthetic, 2026-07-29..09-01)';

COPY INTO BRAINTRUST_SPANS
FROM (
    SELECT
        $1:ID::STRING, $1:XACT_ID::NUMBER(38,0), $1:PAGINATION_KEY::STRING, $1:CREATED::TIMESTAMP_NTZ(6),
        $1:SPAN_ID::STRING, $1:ROOT_SPAN_ID::STRING, TRY_PARSE_JSON($1:SPAN_PARENTS::STRING), $1:IS_ROOT::BOOLEAN,
        $1:PROJECT_ID::STRING, $1:ORG_ID::STRING, $1:LOG_ID::STRING,
        TRY_PARSE_JSON($1:INPUT::STRING), TRY_PARSE_JSON($1:OUTPUT::STRING), TRY_PARSE_JSON($1:EXPECTED::STRING),
        TRY_PARSE_JSON($1:ERROR::STRING), TRY_PARSE_JSON($1:METADATA::STRING), TRY_PARSE_JSON($1:METRICS::STRING),
        TRY_PARSE_JSON($1:SCORES::STRING), TRY_PARSE_JSON($1:SPAN_ATTRIBUTES::STRING), TRY_PARSE_JSON($1:TAGS::STRING),
        TRY_PARSE_JSON($1:AUDIT_DATA::STRING), TRY_PARSE_JSON($1:CONTEXT::STRING), TRY_PARSE_JSON($1:ORIGIN::STRING),
        TRY_PARSE_JSON($1:CLASSIFICATIONS::STRING), TRY_PARSE_JSON($1:COMMENTS::STRING), TRY_PARSE_JSON($1:FACETS::STRING),
        TRY_PARSE_JSON($1:ASYNC_SCORING_STATE::STRING),
        $1:PROJECT_NAME::STRING, $1:EVENT_DT::DATE, $1:SOURCE_SYSTEM::STRING, $1:SOURCE_VERSION_KEY::NUMBER(3,0),
        $1:ROW_HASH::STRING, $1:FIELD_COUNT::NUMBER(38,0), $1:_INGEST_METHOD::STRING, $1:_INGEST_RUN_ID::STRING,
        $1:_INGEST_BATCH_ID::STRING, $1:_SOURCE_FILE::STRING, $1:_LOADED_AT::TIMESTAMP_NTZ(6),
        METADATA$FILENAME
    FROM @SPANS_STAGE
)
FILE_FORMAT = (FORMAT_NAME = 'PARQUET_FF')
ON_ERROR = ABORT_STATEMENT;
