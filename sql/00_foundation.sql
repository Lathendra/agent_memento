-- Schemas, roles, tags and masking policies. Run first; idempotent.
-- Synthetic data, but PHI/PII controls are applied as if it were production.
USE ROLE ATTENDEE_ROLE;
USE WAREHOUSE DEFAULT_WH;
USE DATABASE AGENT_MEMENTO;

CREATE SCHEMA IF NOT EXISTS RAW        COMMENT = 'Landed source data, unchanged';
CREATE SCHEMA IF NOT EXISTS STAGING    COMMENT = 'Typed, stitched, rebuildable';
CREATE SCHEMA IF NOT EXISTS MART       COMMENT = 'Dimensions, facts and aggregates; no raw identifiers';
CREATE SCHEMA IF NOT EXISTS SEMANTIC   COMMENT = 'Semantic views and Cortex Agent';
CREATE SCHEMA IF NOT EXISTS OPS        COMMENT = 'Run log and data quality results; metadata only';
CREATE SCHEMA IF NOT EXISTS GOVERNANCE COMMENT = 'Tags and masking policies';

-- Consumer role: MART and SEMANTIC only, masked values.
CREATE ROLE IF NOT EXISTS AGENT_MEMENTO_ANALYST_R COMMENT = 'Read MART and SEMANTIC; PHI/PII masked';
GRANT ROLE AGENT_MEMENTO_ANALYST_R TO ROLE ATTENDEE_ROLE;
GRANT USAGE ON DATABASE AGENT_MEMENTO TO ROLE AGENT_MEMENTO_ANALYST_R;
GRANT USAGE ON SCHEMA MART TO ROLE AGENT_MEMENTO_ANALYST_R;
GRANT USAGE ON SCHEMA SEMANTIC TO ROLE AGENT_MEMENTO_ANALYST_R;
GRANT USAGE ON WAREHOUSE DEFAULT_WH TO ROLE AGENT_MEMENTO_ANALYST_R;

USE SCHEMA GOVERNANCE;

CREATE TAG IF NOT EXISTS DATA_CLASS_PHI  ALLOWED_VALUES 'TRUE' COMMENT = 'Column holds PHI';
CREATE TAG IF NOT EXISTS DATA_CLASS_PII  ALLOWED_VALUES 'TRUE' COMMENT = 'Column holds PII';
CREATE TAG IF NOT EXISTS HIPAA_DATA_TIER ALLOWED_VALUES 'IDENTIFIED', 'DEIDENTIFIED' COMMENT = 'Table-level HIPAA tier';
CREATE TAG IF NOT EXISTS DATA_DOMAIN     ALLOWED_VALUES 'AGENT_OBSERVABILITY' COMMENT = 'Owning data domain';

-- Clear text only for the pipeline owner role; everyone else (including AGENT_MEMENTO_ANALYST_R) sees redacted values.
CREATE MASKING POLICY IF NOT EXISTS MP_FREE_TEXT_VARIANT AS (v VARIANT) RETURNS VARIANT ->
    CASE WHEN CURRENT_ROLE() = 'ATTENDEE_ROLE' THEN v
         WHEN v IS NULL THEN NULL
         ELSE TO_VARIANT('***REDACTED***') END
    COMMENT = 'Redacts free-text VARIANT payloads (prompts, responses, metadata)';

CREATE MASKING POLICY IF NOT EXISTS MP_FREE_TEXT AS (v STRING) RETURNS STRING ->
    CASE WHEN CURRENT_ROLE() = 'ATTENDEE_ROLE' THEN v
         WHEN v IS NULL THEN NULL
         ELSE '***REDACTED***' END
    COMMENT = 'Redacts free text';

CREATE MASKING POLICY IF NOT EXISTS MP_EMAIL AS (v STRING) RETURNS STRING ->
    CASE WHEN CURRENT_ROLE() = 'ATTENDEE_ROLE' THEN v
         WHEN v IS NULL THEN NULL
         ELSE REGEXP_REPLACE(v, '^[^@]+', '*****') END
    COMMENT = 'Masks the local part of an email address';

CREATE MASKING POLICY IF NOT EXISTS MP_IDENTIFIER AS (v STRING) RETURNS STRING ->
    CASE WHEN CURRENT_ROLE() = 'ATTENDEE_ROLE' THEN v
         WHEN v IS NULL THEN NULL
         ELSE '***REDACTED***' END
    COMMENT = 'Full redaction of direct identifiers (session id, user name)';

-- Session/call key: one-way hash so MART never carries a raw identifier.
CREATE OR REPLACE SECURE FUNCTION FN_CALL_HASH(ROOT_SPAN_ID STRING)
    RETURNS STRING
    COMMENT = 'Deterministic SHA-256 call key derived from ROOT_SPAN_ID'
    AS 'SHA2(''agent_memento|'' || ROOT_SPAN_ID, 256)';
