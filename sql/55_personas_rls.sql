-- Persona roles, row access by customer account, financial masking. Run after sql/50.
-- Re-run after any MART rebuild: CREATE OR REPLACE TABLE drops attached policies.
USE WAREHOUSE DEFAULT_WH;
USE SCHEMA AGENT_MEMENTO.GOVERNANCE;

CREATE ROLE IF NOT EXISTS AM_AGENT_PM_R COMMENT = 'Agent Product Manager: all accounts, financials masked';
CREATE ROLE IF NOT EXISTS AM_CSM_R      COMMENT = 'Customer Success Manager: own book of accounts, financials masked';
CREATE ROLE IF NOT EXISTS AM_FINANCE_R  COMMENT = 'Finance / COGS: all accounts, financials clear';
GRANT ROLE AM_AGENT_PM_R TO ROLE ATTENDEE_ROLE;
GRANT ROLE AM_CSM_R      TO ROLE ATTENDEE_ROLE;
GRANT ROLE AM_FINANCE_R  TO ROLE ATTENDEE_ROLE;

-- Which accounts a restricted role may see (CSM book of business).
CREATE OR REPLACE TABLE ACCOUNT_ACCESS_MAP (
    ROLE_NAME   STRING NOT NULL,
    ACCOUNT_ID  STRING NOT NULL,
    CSM_OWNER   STRING
) COMMENT = 'Role to customer-account entitlements for row access';
INSERT INTO ACCOUNT_ACCESS_MAP
SELECT 'AM_CSM_R', ACCOUNT_ID, CSM_OWNER
FROM AGENT_MEMENTO.MART.DIM_CUSTOMER_ACCOUNT
WHERE CSM_OWNER = 'Priya Shah';

-- Full-visibility roles see every account; any other role sees only its mapped accounts.
CREATE OR REPLACE ROW ACCESS POLICY RAP_ACCOUNT AS (ACCOUNT_ID STRING) RETURNS BOOLEAN ->
    CURRENT_ROLE() IN ('ATTENDEE_ROLE', 'AM_AGENT_PM_R', 'AM_FINANCE_R', 'AGENT_MEMENTO_ANALYST_R')
    OR EXISTS (SELECT 1 FROM AGENT_MEMENTO.GOVERNANCE.ACCOUNT_ACCESS_MAP m
               WHERE m.ROLE_NAME = CURRENT_ROLE() AND m.ACCOUNT_ID = ACCOUNT_ID)
    COMMENT = 'Row access by customer account';

-- Revenue, margin and contract price: clear only to Finance and the pipeline owner.
CREATE OR REPLACE MASKING POLICY MP_FINANCIAL AS (v NUMBER(18,6)) RETURNS NUMBER(18,6) ->
    CASE WHEN CURRENT_ROLE() IN ('ATTENDEE_ROLE', 'AM_FINANCE_R') THEN v ELSE NULL END
    COMMENT = 'Financial amounts visible to Finance only';
CREATE OR REPLACE MASKING POLICY MP_FINANCIAL_PRICE AS (v NUMBER(10,4)) RETURNS NUMBER(10,4) ->
    CASE WHEN CURRENT_ROLE() IN ('ATTENDEE_ROLE', 'AM_FINANCE_R') THEN v ELSE NULL END
    COMMENT = 'Contract price visible to Finance only';

ALTER TABLE AGENT_MEMENTO.MART.FCT_CALL      ADD ROW ACCESS POLICY RAP_ACCOUNT ON (ACCOUNT_ID);
ALTER TABLE AGENT_MEMENTO.MART.FCT_LLM_USAGE ADD ROW ACCESS POLICY RAP_ACCOUNT ON (ACCOUNT_ID);
ALTER TABLE AGENT_MEMENTO.MART.FCT_TOOL_CALL ADD ROW ACCESS POLICY RAP_ACCOUNT ON (ACCOUNT_ID);
ALTER TABLE AGENT_MEMENTO.MART.AGG_ORG_DAY   ADD ROW ACCESS POLICY RAP_ACCOUNT ON (ACCOUNT_ID);
ALTER TABLE AGENT_MEMENTO.MART.DIM_CUSTOMER_ACCOUNT ADD ROW ACCESS POLICY RAP_ACCOUNT ON (ACCOUNT_ID);

ALTER TABLE AGENT_MEMENTO.MART.FCT_CALL MODIFY
    COLUMN REVENUE_AMOUNT      SET MASKING POLICY MP_FINANCIAL,
    COLUMN GROSS_MARGIN_AMOUNT SET MASKING POLICY MP_FINANCIAL;
ALTER TABLE AGENT_MEMENTO.MART.AGG_ORG_DAY MODIFY
    COLUMN REVENUE_AMOUNT      SET MASKING POLICY MP_FINANCIAL,
    COLUMN GROSS_MARGIN_AMOUNT SET MASKING POLICY MP_FINANCIAL;
ALTER TABLE AGENT_MEMENTO.MART.DIM_CUSTOMER_ACCOUNT MODIFY
    COLUMN CONTRACT_PRICE_PER_MIN_AMOUNT SET MASKING POLICY MP_FINANCIAL_PRICE;

