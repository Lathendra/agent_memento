-- Supervisor output: margin signals are Finance-only; account-level signals follow the account map.
-- Requires OPS tables from 65_supervisor.sql (re-run this block after 65).
CREATE OR REPLACE ROW ACCESS POLICY AGENT_MEMENTO.GOVERNANCE.RAP_OPS_SIGNAL
  AS (SIGNAL_TYPE STRING, ENTITY_TYPE STRING, ENTITY_ID STRING) RETURNS BOOLEAN ->
  CURRENT_ROLE() IN ('ATTENDEE_ROLE','AM_FINANCE_R','AGENT_MEMENTO_ANALYST_R')
  OR (SIGNAL_TYPE <> 'NEGATIVE_MARGIN_ACCOUNT' AND (
        CURRENT_ROLE() = 'AM_AGENT_PM_R'
        OR ENTITY_TYPE <> 'ACCOUNT'
        OR EXISTS (SELECT 1 FROM AGENT_MEMENTO.GOVERNANCE.ACCOUNT_ACCESS_MAP m
                   WHERE m.ROLE_NAME = CURRENT_ROLE() AND m.ACCOUNT_ID = ENTITY_ID)))
  COMMENT = 'Supervisor signals/actions: margin is Finance-only; account rows follow ACCOUNT_ACCESS_MAP';

ALTER TABLE AGENT_MEMENTO.OPS.AGENT_ACTIONS ADD ROW ACCESS POLICY AGENT_MEMENTO.GOVERNANCE.RAP_OPS_SIGNAL ON (SIGNAL_TYPE, ENTITY_TYPE, ENTITY_ID);
ALTER TABLE AGENT_MEMENTO.OPS.AGENT_SIGNALS ADD ROW ACCESS POLICY AGENT_MEMENTO.GOVERNANCE.RAP_OPS_SIGNAL ON (SIGNAL_TYPE, ENTITY_TYPE, ENTITY_ID);
