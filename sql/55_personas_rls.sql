GRANT USAGE ON SCHEMA AGENT_MEMENTO.SEMANTIC TO ROLE AM_FINANCE_R;
GRANT USAGE ON SCHEMA AGENT_MEMENTO.OPS TO ROLE AM_AGENT_PM_R;
