-- AGG, governance (tags + masking on PHI/PII columns) and consumer grants.
USE WAREHOUSE DEFAULT_WH;
USE SCHEMA AGENT_MEMENTO.MART;

-- Additive counts and sums only; rates are computed at query time.
DROP TABLE IF EXISTS AGG_CALL_DAY;
CREATE OR REPLACE TABLE AGG_ORG_DAY
COMMENT = 'Daily call KPIs and economics by account, model, intent and outcome (additive measures)'
AS
SELECT
    CALL_DATE_PT, ORG_ID, ACCOUNT_ID, MODEL_NAME, INTENT_TAG, OUTCOME_CODE,
    COUNT(*)                         AS CALL_COUNT,
    COUNT_IF(ERROR_SPAN_COUNT > 0)   AS CALL_WITH_ERROR_COUNT,
    COUNT_IF(IS_COST_ANOMALY)        AS COST_ANOMALY_COUNT,
    COUNT_IF(IS_DURATION_ANOMALY)    AS DURATION_ANOMALY_COUNT,
    SUM(DURATION_SECONDS)            AS DURATION_SECONDS,
    SUM(BILLABLE_MINUTES)            AS BILLABLE_MINUTES,
    SUM(SPAN_COUNT)                  AS SPAN_COUNT,
    SUM(LLM_CALL_COUNT)              AS LLM_CALL_COUNT,
    SUM(TOOL_CALL_COUNT)             AS TOOL_CALL_COUNT,
    SUM(ERROR_SPAN_COUNT)            AS ERROR_SPAN_COUNT,
    SUM(TOOL_ERROR_COUNT)            AS TOOL_ERROR_COUNT,
    SUM(LLM_ERROR_COUNT)             AS LLM_ERROR_COUNT,
    SUM(TOTAL_TOKEN_COUNT)           AS TOTAL_TOKEN_COUNT,
    SUM(COST_AMOUNT)                 AS COST_AMOUNT,
    SUM(TELEPHONY_COST_AMOUNT)       AS TELEPHONY_COST_AMOUNT,
    SUM(COGS_AMOUNT)                 AS COGS_AMOUNT,
    SUM(REVENUE_AMOUNT)              AS REVENUE_AMOUNT,
    SUM(GROSS_MARGIN_AMOUNT)         AS GROSS_MARGIN_AMOUNT
FROM FCT_CALL
GROUP BY ALL;

-- PHI / PII column tags and masking. Synthetic data, controls applied as for production.
USE SCHEMA AGENT_MEMENTO.GOVERNANCE;

ALTER TABLE AGENT_MEMENTO.RAW.BRAINTRUST_SPANS MODIFY
    COLUMN INPUT      SET MASKING POLICY MP_FREE_TEXT_VARIANT FORCE,
    COLUMN OUTPUT     SET MASKING POLICY MP_FREE_TEXT_VARIANT FORCE,
    COLUMN METADATA   SET MASKING POLICY MP_FREE_TEXT_VARIANT FORCE,
    COLUMN AUDIT_DATA SET MASKING POLICY MP_FREE_TEXT_VARIANT FORCE,
    COLUMN ERROR      SET MASKING POLICY MP_FREE_TEXT_VARIANT FORCE;
ALTER TABLE AGENT_MEMENTO.RAW.BRAINTRUST_SPANS MODIFY
    COLUMN INPUT      SET TAG DATA_CLASS_PHI = 'TRUE',
    COLUMN OUTPUT     SET TAG DATA_CLASS_PHI = 'TRUE',
    COLUMN METADATA   SET TAG DATA_CLASS_PHI = 'TRUE', DATA_CLASS_PII = 'TRUE',
    COLUMN AUDIT_DATA SET TAG DATA_CLASS_PHI = 'TRUE',
    COLUMN ERROR      SET TAG DATA_CLASS_PHI = 'TRUE';

ALTER TABLE AGENT_MEMENTO.STAGING.SPANS MODIFY
    COLUMN SESSION_ID    SET MASKING POLICY MP_IDENTIFIER FORCE,
    COLUMN USER_NAME     SET MASKING POLICY MP_IDENTIFIER FORCE,
    COLUMN USER_EMAIL    SET MASKING POLICY MP_EMAIL FORCE,
    COLUMN ERROR_MESSAGE SET MASKING POLICY MP_FREE_TEXT FORCE,
    COLUMN INPUT         SET MASKING POLICY MP_FREE_TEXT_VARIANT FORCE,
    COLUMN OUTPUT        SET MASKING POLICY MP_FREE_TEXT_VARIANT FORCE;
ALTER TABLE AGENT_MEMENTO.STAGING.SPANS MODIFY
    COLUMN SESSION_ID    SET TAG DATA_CLASS_PHI = 'TRUE',
    COLUMN USER_NAME     SET TAG DATA_CLASS_PII = 'TRUE',
    COLUMN USER_EMAIL    SET TAG DATA_CLASS_PII = 'TRUE',
    COLUMN ERROR_MESSAGE SET TAG DATA_CLASS_PHI = 'TRUE',
    COLUMN INPUT         SET TAG DATA_CLASS_PHI = 'TRUE',
    COLUMN OUTPUT        SET TAG DATA_CLASS_PHI = 'TRUE';

-- MART holds hashes only; the call hash is still tagged PHI (re-identifiable via STAGING).
ALTER TABLE AGENT_MEMENTO.MART.FCT_CALL      MODIFY COLUMN CALL_HASH SET TAG DATA_CLASS_PHI = 'TRUE';
ALTER TABLE AGENT_MEMENTO.MART.FCT_LLM_USAGE MODIFY COLUMN CALL_HASH SET TAG DATA_CLASS_PHI = 'TRUE';
ALTER TABLE AGENT_MEMENTO.MART.FCT_TOOL_CALL MODIFY COLUMN CALL_HASH SET TAG DATA_CLASS_PHI = 'TRUE';

ALTER TABLE AGENT_MEMENTO.MART.FCT_CALL      SET TAG HIPAA_DATA_TIER = 'IDENTIFIED', DATA_DOMAIN = 'AGENT_OBSERVABILITY';
ALTER TABLE AGENT_MEMENTO.MART.FCT_LLM_USAGE SET TAG HIPAA_DATA_TIER = 'IDENTIFIED', DATA_DOMAIN = 'AGENT_OBSERVABILITY';
ALTER TABLE AGENT_MEMENTO.MART.FCT_TOOL_CALL SET TAG HIPAA_DATA_TIER = 'IDENTIFIED', DATA_DOMAIN = 'AGENT_OBSERVABILITY';
ALTER TABLE AGENT_MEMENTO.MART.AGG_ORG_DAY   SET TAG HIPAA_DATA_TIER = 'DEIDENTIFIED', DATA_DOMAIN = 'AGENT_OBSERVABILITY';

