-- Data quality and trust checks. Every row MUST return STATUS = 'PASS'. Run after any rebuild.
-- Part 1 runs as ATTENDEE_ROLE. Part 2 (RL*) runs once per persona role and checks row access and masking.
USE WAREHOUSE DEFAULT_WH;
USE ROLE ATTENDEE_ROLE;

SELECT CHECK_NAME, EXPECTED, ACTUAL, IFF(EXPECTED = ACTUAL, 'PASS', 'FAIL') AS STATUS FROM (
    SELECT 'DQ01 RAW spans = STAGING spans' AS CHECK_NAME,
           (SELECT COUNT(*) FROM AGENT_MEMENTO.RAW.BRAINTRUST_SPANS) AS EXPECTED,
           (SELECT COUNT(*) FROM AGENT_MEMENTO.STAGING.SPANS) AS ACTUAL
    UNION ALL SELECT 'DQ02 one row per span ID', 0,
           (SELECT COUNT(*) - COUNT(DISTINCT SPAN_ROW_ID) FROM AGENT_MEMENTO.STAGING.SPANS)
    UNION ALL SELECT 'DQ03 FCT_CALL = distinct traces',
           (SELECT COUNT(DISTINCT ROOT_SPAN_ID) FROM AGENT_MEMENTO.STAGING.SPANS),
           (SELECT COUNT(*) FROM AGENT_MEMENTO.MART.FCT_CALL)
    UNION ALL SELECT 'DQ04 unique CALL_HASH', 0,
           (SELECT COUNT(*) - COUNT(DISTINCT CALL_HASH) FROM AGENT_MEMENTO.MART.FCT_CALL)
    UNION ALL SELECT 'DQ05 call spans sum = spans',
           (SELECT COUNT(*) FROM AGENT_MEMENTO.STAGING.SPANS),
           (SELECT SUM(SPAN_COUNT) FROM AGENT_MEMENTO.MART.FCT_CALL)
    UNION ALL SELECT 'DQ06 FCT_LLM_USAGE = llm spans',
           (SELECT COUNT_IF(SPAN_TYPE = 'llm') FROM AGENT_MEMENTO.STAGING.SPANS),
           (SELECT COUNT(*) FROM AGENT_MEMENTO.MART.FCT_LLM_USAGE)
    UNION ALL SELECT 'DQ07 FCT_TOOL_CALL = tool spans',
           (SELECT COUNT_IF(SPAN_TYPE = 'tool') FROM AGENT_MEMENTO.STAGING.SPANS),
           (SELECT COUNT(*) FROM AGENT_MEMENTO.MART.FCT_TOOL_CALL)
    UNION ALL SELECT 'DQ08 call tokens = LLM tokens',
           (SELECT SUM(TOTAL_TOKEN_COUNT) FROM AGENT_MEMENTO.MART.FCT_LLM_USAGE),
           (SELECT SUM(TOTAL_TOKEN_COUNT) FROM AGENT_MEMENTO.MART.FCT_CALL)
    UNION ALL SELECT 'DQ09 call cost = LLM cost (cents)',
           (SELECT ROUND(SUM(COST_AMOUNT) * 100) FROM AGENT_MEMENTO.MART.FCT_LLM_USAGE),
           (SELECT ROUND(SUM(COST_AMOUNT) * 100) FROM AGENT_MEMENTO.MART.FCT_CALL)
    UNION ALL SELECT 'DQ10 AGG calls = FCT_CALL',
           (SELECT COUNT(*) FROM AGENT_MEMENTO.MART.FCT_CALL),
           (SELECT SUM(CALL_COUNT) FROM AGENT_MEMENTO.MART.AGG_ORG_DAY)
    UNION ALL SELECT 'DQ11 orphan dimension keys', 0,
           (SELECT COUNT_IF(m.MODEL_NAME IS NULL) + COUNT_IF(i.INTENT_TAG IS NULL) + COUNT_IF(o.OUTCOME_CODE IS NULL)
                 + COUNT_IF(d.DATE_KEY IS NULL) + COUNT_IF(a.ACCOUNT_ID IS NULL)
              FROM AGENT_MEMENTO.MART.FCT_CALL f
              LEFT JOIN AGENT_MEMENTO.MART.DIM_LLM_MODEL m USING (MODEL_NAME)
              LEFT JOIN AGENT_MEMENTO.MART.DIM_INTENT i USING (INTENT_TAG)
              LEFT JOIN AGENT_MEMENTO.MART.DIM_OUTCOME o USING (OUTCOME_CODE)
              LEFT JOIN AGENT_MEMENTO.MART.DIM_DATE d ON d.DATE_KEY = f.CALL_DATE_PT
              LEFT JOIN AGENT_MEMENTO.MART.DIM_CUSTOMER_ACCOUNT a ON a.ACCOUNT_ID = f.ACCOUNT_ID)
    UNION ALL SELECT 'DQ12 negative durations', 0,
           (SELECT COUNT_IF(DURATION_SECONDS < 0) FROM AGENT_MEMENTO.MART.FCT_CALL)
    UNION ALL SELECT 'DQ13 8 customer accounts, 1 org', 81,
           (SELECT COUNT(*) * 10 FROM AGENT_MEMENTO.MART.DIM_CUSTOMER_ACCOUNT) + (SELECT COUNT(*) FROM AGENT_MEMENTO.MART.DIM_ORGANIZATION)
    UNION ALL SELECT 'DQ14 span facts carry the call account', 0,
           (SELECT COUNT(*) FROM AGENT_MEMENTO.MART.FCT_LLM_USAGE u JOIN AGENT_MEMENTO.MART.FCT_CALL c USING (CALL_HASH) WHERE u.ACCOUNT_ID <> c.ACCOUNT_ID)
    UNION ALL SELECT 'DQ15 revenue = minutes x price (mismatches)', 0,
           (SELECT COUNT_IF(ABS(f.REVENUE_AMOUNT - f.BILLABLE_MINUTES * a.CONTRACT_PRICE_PER_MIN_AMOUNT) > 0.000001)
              FROM AGENT_MEMENTO.MART.FCT_CALL f JOIN AGENT_MEMENTO.MART.DIM_CUSTOMER_ACCOUNT a USING (ACCOUNT_ID))
    UNION ALL SELECT 'DQ16 COGS = model + telephony (mismatches)', 0,
           (SELECT COUNT_IF(ABS(COGS_AMOUNT - COST_AMOUNT - TELEPHONY_COST_AMOUNT) > 0.000001) FROM AGENT_MEMENTO.MART.FCT_CALL)
    UNION ALL SELECT 'DQ17 margin = revenue - COGS (mismatches)', 0,
           (SELECT COUNT_IF(ABS(GROSS_MARGIN_AMOUNT - (REVENUE_AMOUNT - COGS_AMOUNT)) > 0.00001) FROM AGENT_MEMENTO.MART.FCT_CALL)
    UNION ALL SELECT 'DQ18 AGG revenue = FCT revenue (cents)',
           (SELECT ROUND(SUM(REVENUE_AMOUNT) * 100) FROM AGENT_MEMENTO.MART.FCT_CALL),
           (SELECT ROUND(SUM(REVENUE_AMOUNT) * 100) FROM AGENT_MEMENTO.MART.AGG_ORG_DAY)
    UNION ALL SELECT 'DQ19 at least 2 negative-margin accounts', 1,
           (SELECT IFF(COUNT(*) >= 2, 1, 0) FROM (SELECT ACCOUNT_ID FROM AGENT_MEMENTO.MART.FCT_CALL GROUP BY 1 HAVING SUM(GROSS_MARGIN_AMOUNT) < 0))
    UNION ALL SELECT 'DQ20 every action has a signal', 0,
           (SELECT COUNT(*) FROM AGENT_MEMENTO.OPS.AGENT_ACTIONS a LEFT JOIN AGENT_MEMENTO.OPS.AGENT_SIGNALS s USING (SIGNAL_KEY) WHERE s.SIGNAL_KEY IS NULL)
    UNION ALL SELECT 'DQ21 one action per signal', 0,
           (SELECT COUNT(*) - COUNT(DISTINCT SIGNAL_KEY) FROM AGENT_MEMENTO.OPS.AGENT_ACTIONS)
    UNION ALL SELECT 'DQ22 action savings = SQL impact (mismatches)', 0,
           (SELECT COUNT(*) FROM AGENT_MEMENTO.OPS.AGENT_ACTIONS a JOIN AGENT_MEMENTO.OPS.AGENT_SIGNALS s USING (SIGNAL_KEY)
             WHERE NOT EQUAL_NULL(a.PROJECTED_SAVINGS_AMOUNT, s.IMPACT_AMOUNT))
    UNION ALL SELECT 'DQ23 valid action status', 0,
           (SELECT COUNT_IF(STATUS NOT IN ('PROPOSED', 'APPROVED', 'REJECTED')
                         OR (STATUS <> 'PROPOSED' AND (DECIDED_ROLE IS NULL OR DECIDED_TS_PT IS NULL))) FROM AGENT_MEMENTO.OPS.AGENT_ACTIONS)
    UNION ALL SELECT 'DQ24 every supervisor run succeeded', 0,
           (SELECT COUNT_IF(STATUS <> 'SUCCEEDED') FROM AGENT_MEMENTO.OPS.AGENT_RUN_LOG)
    UNION ALL SELECT 'DQ25 persona evals passed',
           (SELECT COUNT(*) FROM AGENT_MEMENTO.OPS.AGENT_EVAL_RESULT),
           (SELECT COUNT_IF(IS_PASS) FROM AGENT_MEMENTO.OPS.AGENT_EVAL_RESULT)
) c
ORDER BY CHECK_NAME;

-- Part 2: row access and masking per persona. Expected: PM 243036 calls / 8 accounts / 0 revenue visible;
-- CSM 107213 / 3 / 0; Finance 243036 / 8 / 243036.
USE ROLE AM_AGENT_PM_R;
SELECT 'RL01 Agent PM' AS CHECK_NAME, COUNT(*) AS CALLS, COUNT(DISTINCT ACCOUNT_ID) AS ACCOUNTS, COUNT(REVENUE_AMOUNT) AS REVENUE_VISIBLE,
       IFF(COUNT(*) = 243036 AND COUNT(DISTINCT ACCOUNT_ID) = 8 AND COUNT(REVENUE_AMOUNT) = 0, 'PASS', 'FAIL') AS STATUS
FROM AGENT_MEMENTO.MART.FCT_CALL;
USE ROLE AM_CSM_R;
SELECT 'RL02 CSM' AS CHECK_NAME, COUNT(*) AS CALLS, COUNT(DISTINCT ACCOUNT_ID) AS ACCOUNTS, COUNT(REVENUE_AMOUNT) AS REVENUE_VISIBLE,
       IFF(COUNT(DISTINCT ACCOUNT_ID) = 3 AND COUNT(REVENUE_AMOUNT) = 0, 'PASS', 'FAIL') AS STATUS
FROM AGENT_MEMENTO.MART.FCT_CALL;
USE ROLE AM_FINANCE_R;
SELECT 'RL03 Finance' AS CHECK_NAME, COUNT(*) AS CALLS, COUNT(DISTINCT ACCOUNT_ID) AS ACCOUNTS, COUNT(REVENUE_AMOUNT) AS REVENUE_VISIBLE,
       IFF(COUNT(*) = 243036 AND COUNT(DISTINCT ACCOUNT_ID) = 8 AND COUNT(REVENUE_AMOUNT) = 243036, 'PASS', 'FAIL') AS STATUS
FROM AGENT_MEMENTO.MART.FCT_CALL;
USE ROLE ATTENDEE_ROLE;

-- RL04: supervisor output follows persona access. Run as AM_CSM_R and AM_AGENT_PM_R; expect MARGIN = 0 and OTHER_ACCTS = 0.
SELECT 'RL04' AS CHECK_ID, CURRENT_ROLE() AS RUN_ROLE, COUNT(*) AS N,
       COUNT_IF(SIGNAL_TYPE = 'NEGATIVE_MARGIN_ACCOUNT') AS MARGIN,
       COUNT_IF(ENTITY_TYPE = 'ACCOUNT' AND ENTITY_ID NOT IN (SELECT ACCOUNT_ID FROM AGENT_MEMENTO.GOVERNANCE.ACCOUNT_ACCESS_MAP WHERE ROLE_NAME = CURRENT_ROLE())) AS OTHER_ACCTS,
       IFF(CURRENT_ROLE() IN ('AM_FINANCE_R','ATTENDEE_ROLE') OR MARGIN = 0, 'PASS', 'FAIL') AS RESULT
FROM AGENT_MEMENTO.OPS.AGENT_ACTIONS;
